const legacyOfficialEntries = Object.entries(legacyOfficialMediaUrls);

export function getManagedLegacyOfficialUrl(value: string) {
  return legacyOfficialMediaUrls[value as keyof typeof legacyOfficialMediaUrls] ?? value;
}

export function replaceLegacyOfficialUrlsInString(value: string) {
  if (!value.includes("/official/")) {
    return value;
  }

  let nextValue = value;

  for (const [legacyPath, managedUrl] of legacyOfficialEntries) {
    nextValue = nextValue.split(legacyPath).join(managedUrl);
  }

  return nextValue;
}

export function replaceLegacyOfficialUrlsInJson<T>(value: T): T {
  if (typeof value === "string") {
    return replaceLegacyOfficialUrlsInString(value) as T;
  }

  if (value instanceof Date) {
    return value;
  }

  if (Array.isArray(value)) {
    return value.map((item) => replaceLegacyOfficialUrlsInJson(item)) as T;
  }

  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, entryValue]) => [key, replaceLegacyOfficialUrlsInJson(entryValue)]),
    ) as T;
  }

  return value;
}

