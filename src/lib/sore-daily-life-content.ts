export function splitSoreDailyLifeStoryBody(body: string) {
  const normalized = body.replace(/\s+/g, " ").trim();
  const sentences = normalized.split(/(?<=[。！？])/u).map((sentence) => sentence.trim()).filter(Boolean);

  if (sentences.length <= 3) {
    return [normalized];
  }

  const chunkSize = Math.max(2, Math.ceil(sentences.length / 4));
  const paragraphs: string[] = [];

  for (let index = 0; index < sentences.length; index += chunkSize) {
    paragraphs.push(sentences.slice(index, index + chunkSize).join(""));
  }

  return paragraphs;
}